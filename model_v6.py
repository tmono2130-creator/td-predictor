"""
MODEL V6 — evaluates fitted candidates on a strictly later, held-out season.

Training seasons must all precede the holdout. The baseline calibrator is fit
on those earlier seasons only. Inputs must be generated by the guarded
build_training_data.py workflow and carry completed-week, player/game,
retrospective-provenance, and pre-week feature-cutoff fields. Historical
reconstructions are not archived pregame forecasts.

Metrics include Brier score, log loss, AUC, average top-N scoring, and a
calibration table. This script does not change V5 weights or deploy a model.
"""

import argparse

import numpy as np
import pandas as pd

try:
    from sklearn.linear_model import LogisticRegression
    from sklearn.ensemble import HistGradientBoostingClassifier
    from sklearn.isotonic import IsotonicRegression
    from sklearn.metrics import brier_score_loss, log_loss, roc_auc_score
    from sklearn.preprocessing import StandardScaler
    from sklearn.impute import SimpleImputer
except ImportError:
    raise SystemExit("scikit-learn required. Run: python -m pip install scikit-learn")

from evaluation_utils import validate_training_data_frame


EXCLUDE = {"player_id", "game_id", "player", "team", "position", "opponent",
           "season", "week", "actual_td", "td_score", "td_estimate",
           "week_complete", "prediction_origin", "prediction_generated_at",
           "feature_cutoff_season", "feature_cutoff_week"}


def load_data(path):
    df = pd.read_csv(path)
    try:
        return validate_training_data_frame(df)
    except ValueError as e:
        raise SystemExit(f"{path} is not valid evaluation data: {e}") from e


def feature_columns(df):
    return [c for c in df.columns if c not in EXCLUDE and pd.api.types.is_numeric_dtype(df[c])]


def chronological_holdout(df, holdout_season):
    """Use only strictly earlier seasons for fitting; never train on future years."""
    train = df[df["season"] < holdout_season].copy()
    test = df[df["season"] == holdout_season].copy()
    if train.empty or test.empty:
        raise ValueError(
            f"Need complete data from at least one earlier season and the holdout. "
            f"Seasons present: {sorted(df['season'].unique())}"
        )
    return train, test


def evaluate(name, y_true, y_prob, weeks=None):
    out = {
        "model": name,
        "brier": brier_score_loss(y_true, y_prob),
        "log_loss": log_loss(y_true, np.clip(y_prob, 1e-9, 1 - 1e-9)),
        "auc": roc_auc_score(y_true, y_prob) if len(set(y_true)) > 1 else float("nan"),
    }
    if weeks is not None:
        df = pd.DataFrame({"y": y_true, "p": y_prob, "week": weeks})
        for n in (10, 20, 30):
            hits = df.groupby("week", group_keys=False).apply(
                lambda g: g.nlargest(n, "p")["y"].sum()
            )
            out[f"top{n}_per_week"] = hits.mean()
    return out


def calibration_table(y_true, y_prob, bins=10):
    df = pd.DataFrame({"y": y_true, "p": y_prob})
    df["bucket"] = pd.qcut(df["p"], q=bins, duplicates="drop")
    return df.groupby("bucket", observed=True).agg(
        n=("y", "size"),
        avg_predicted_pct=("p", lambda x: x.mean() * 100),
        actual_rate_pct=("y", lambda x: x.mean() * 100),
    ).reset_index()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=str, default="training_data.csv")
    parser.add_argument("--holdout", type=int, required=True,
                         help="Season to hold out entirely for testing")
    args = parser.parse_args()

    df = load_data(args.data)
    feats = feature_columns(df)
    print(f"Loaded {len(df):,} rows, {len(feats)} features.")
    print(f"Positive rate: {df['actual_td'].mean() * 100:.2f}%")

    # Strict forward holdout: no later seasons may train a model evaluated on an earlier year.
    try:
        train, test = chronological_holdout(df, args.holdout)
    except ValueError as e:
        raise SystemExit(str(e)) from e

    print(f"\nTrain: {len(train):,} rows (strictly earlier seasons {sorted(train['season'].unique())})")
    print(f"Test:  {len(test):,} rows (season {args.holdout}, held out)\n")
    print("All rows are retrospective reconstructions with features cut off before the target week.")

    imputer = SimpleImputer(strategy="median")
    X_train = imputer.fit_transform(train[feats])
    X_test = imputer.transform(test[feats])
    y_train, y_test = train["actual_td"].values, test["actual_td"].values
    test_weeks = test["week"].values

    results = []

    # --- Baseline: V5 ranking score calibrated on earlier seasons only --
    # The checked-in fixed td_estimate curve was fit on 2025 data, so it is
    # not an honest baseline for a 2024 or 2025 holdout. Fit this calibrator
    # on the training years, then evaluate it only on the later held-out year.
    baseline_calibrator = IsotonicRegression(y_min=1e-6, y_max=1 - 1e-6, out_of_bounds="clip")
    baseline_calibrator.fit(train["td_score"].values, train["actual_td"].values)
    baseline_prob = baseline_calibrator.predict(test["td_score"].values)
    results.append(evaluate("V5 score + prior-season calibration", y_test, baseline_prob, test_weeks))

    # --- Logistic regression --------------------------------------------
    scaler = StandardScaler()
    X_train_s = scaler.fit_transform(X_train)
    X_test_s = scaler.transform(X_test)

    logit = LogisticRegression(max_iter=2000, C=1.0)  # C=1.0 -> L2 regularization on
    logit.fit(X_train_s, y_train)
    logit_prob = logit.predict_proba(X_test_s)[:, 1]
    results.append(evaluate("Logistic regression", y_test, logit_prob, test_weeks))

    # --- Gradient boosting ----------------------------------------------
    gbm = HistGradientBoostingClassifier(
        max_depth=3, max_iter=200, learning_rate=0.05,
        l2_regularization=1.0, random_state=0,
    )
    gbm.fit(X_train, y_train)
    gbm_prob = gbm.predict_proba(X_test)[:, 1]
    results.append(evaluate("Gradient boosting", y_test, gbm_prob, test_weeks))

    # --- Report -----------------------------------------------------------
    print("=" * 78)
    print("MODEL COMPARISON (held-out season only)")
    print("=" * 78)
    res_df = pd.DataFrame(results)
    print(res_df.to_string(index=False))
    print("\nBrier and log_loss: LOWER is better. AUC and topN: HIGHER is better.")

    print("\n" + "=" * 78)
    print("LOGISTIC REGRESSION — FEATURE COEFFICIENTS")
    print("=" * 78)
    coefs = pd.Series(logit.coef_[0], index=feats).sort_values(key=abs, ascending=False)
    print(coefs.to_string())
    print("\n(Standardized coefficients — magnitude is comparable across features.")
    print(" Near-zero = the model found no use for it, even with it available.)")

    print("\n" + "=" * 78)
    print("CALIBRATION — best model by Brier score")
    print("=" * 78)
    best_idx = int(np.argmin([r["brier"] for r in results]))
    best_name = results[best_idx]["model"]
    best_prob = {"V5 score + prior-season calibration": baseline_prob,
                  "Logistic regression": logit_prob,
                  "Gradient boosting": gbm_prob}[best_name]
    print(f"Best: {best_name}\n")
    print(calibration_table(y_test, best_prob).to_string(index=False))

    out_path = f"model_v6_predictions_{args.holdout}.csv"
    test_out = test[["player_id", "game_id", "player", "team", "position", "season", "week", "actual_td"]].copy()
    test_out["v5_score_calibrated_pct"] = baseline_prob * 100
    test_out["logit_prob_pct"] = logit_prob * 100
    test_out["gbm_prob_pct"] = gbm_prob * 100
    test_out.to_csv(out_path, index=False)
    print(f"\nPer-player predictions saved to: {out_path}")

    print("\nIF a fitted model wins clearly on Brier AND top-N, that's your case for")
    print("replacing the hand-weighted composite. If they're close, prefer logistic")
    print("regression (interpretable, less overfit-prone on a ~2-3% positive rate),")
    print("and consider that the current composite holding its own is a real result too.")


if __name__ == "__main__":
    main()